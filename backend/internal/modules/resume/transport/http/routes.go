package http

import "github.com/gin-gonic/gin"

func RegisterRoutes(handler *Handler, api *gin.RouterGroup, lk *gin.RouterGroup) {
	lk.GET("/resumes", handler.ListResumes)
	lk.POST("/resumes", handler.CreateResumeRoot)
	lk.GET("/resumes/:resumeId", handler.GetResumeRoot)
	lk.PUT("/resumes/:resumeId", handler.UpdateResumeRoot)
	lk.DELETE("/resumes/:resumeId", handler.DeleteResumeRoot)
	lk.POST("/resume/:resumeId/profile", handler.CreateResumeProfile)
	lk.GET("/resume/:resumeId/profile", handler.GetResumeProfile)
	lk.PUT("/resume/:resumeId/profile", handler.UpdateResumeProfile)
	lk.POST("/resume/:resumeId/contacts", handler.CreateResumeContacts)
	lk.GET("/resume/:resumeId/contacts", handler.GetResumeContacts)
	lk.PUT("/resume/:resumeId/contacts", handler.UpdateResumeContacts)
	lk.POST("/resume/:resumeId/skills", handler.CreateSkills)
	lk.GET("/resume/:resumeId/skills", handler.GetSkills)
	lk.PUT("/resume/:resumeId/skills", handler.UpdateSkills)
	lk.POST("/resume/:resumeId/languages", handler.CreateLanguage)
	lk.GET("/resume/:resumeId/languages", handler.ListLanguages)
	lk.GET("/resume/:resumeId/languages/:languageId", handler.GetLanguage)
	lk.PUT("/resume/:resumeId/languages/:languageId", handler.UpdateLanguage)
	lk.DELETE("/resume/:resumeId/languages/:languageId", handler.DeleteLanguage)
	lk.POST("/resume/:resumeId/technologies", handler.CreateTechnology)
	lk.GET("/resume/:resumeId/technologies", handler.ListTechnologies)
	lk.GET("/resume/:resumeId/technologies/:technologyId", handler.GetTechnology)
	lk.PUT("/resume/:resumeId/technologies/:technologyId", handler.UpdateTechnology)
	lk.DELETE("/resume/:resumeId/technologies/:technologyId", handler.DeleteTechnology)
	lk.POST("/resume/:resumeId/experiences", handler.CreateExperience)
	lk.GET("/resume/:resumeId/experiences", handler.ListExperiences)
	lk.GET("/resume/:resumeId/experiences/:experienceId", handler.GetExperience)
	lk.PUT("/resume/:resumeId/experiences/:experienceId", handler.UpdateExperience)
	lk.DELETE("/resume/:resumeId/experiences/:experienceId", handler.DeleteExperience)
	lk.POST("/resume/:resumeId/educations", handler.CreateEducation)
	lk.GET("/resume/:resumeId/educations", handler.ListEducations)
	lk.GET("/resume/:resumeId/educations/:educationId", handler.GetEducation)
	lk.PUT("/resume/:resumeId/educations/:educationId", handler.UpdateEducation)
	lk.DELETE("/resume/:resumeId/educations/:educationId", handler.DeleteEducation)
	lk.POST("/resume/:resumeId/courses", handler.CreateCourse)
	lk.GET("/resume/:resumeId/courses", handler.ListCourses)
	lk.GET("/resume/:resumeId/courses/:courseId", handler.GetCourse)
	lk.PUT("/resume/:resumeId/courses/:courseId", handler.UpdateCourse)
	lk.DELETE("/resume/:resumeId/courses/:courseId", handler.DeleteCourse)
	lk.POST("/resume/:resumeId/activities", handler.CreateActivity)
	lk.GET("/resume/:resumeId/activities", handler.ListActivities)
	lk.GET("/resume/:resumeId/activities/:activityId", handler.GetActivity)
	lk.PUT("/resume/:resumeId/activities/:activityId", handler.UpdateActivity)
	lk.DELETE("/resume/:resumeId/activities/:activityId", handler.DeleteActivity)
	lk.POST("/resume/:resumeId/projects", handler.CreateProject)
	lk.GET("/resume/:resumeId/projects", handler.ListProjects)
	lk.GET("/resume/:resumeId/projects/:projectId", handler.GetProject)
	lk.PUT("/resume/:resumeId/projects/:projectId", handler.UpdateProject)
	lk.DELETE("/resume/:resumeId/projects/:projectId", handler.DeleteProject)
	lk.GET("/resume/:resumeId", handler.GetResume)
	lk.POST("/resume", handler.CreateResume)
	lk.PUT("/resume/:resumeId", handler.UpdateResume)
	lk.PATCH("/resume/:resumeId", handler.PatchResume)
	api.GET("/cv/:resumeId", handler.GetPublicResume)
}
